// ファイル保存(n.q 書き出しに使用)
int file_save(const char* fn, void* rp, int size) {
	FILE *fp = fopen(fn, "wb");
	if (!fp) {
		printf("%s を開けませんでした。", fn);
		return (-1);
	}
	fwrite(rp, size, 1, fp);
	fclose(fp);
	return size;
}
